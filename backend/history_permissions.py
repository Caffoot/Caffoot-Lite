"""Permission-filtered inventory history for read-only API responses.

Keep stored events intact. Filter only the projected response so permission
changes apply immediately without a schema migration or history rewrite.
"""
import json

from .equipment_lifecycle import DEVICE_AUDIT_REASON, FIRST_SERVICE_AUDIT_REASON, SETTINGS_AUDIT_REASON
from .equipment_suppliers import SUPPLIER_AUDIT_REASON
from .permissions import can_access, feature_enabled
from .service_desk_settings import CALENDAR_AUDIT_REASON, CATEGORY_AUDIT_REASON
from .subnet_validation import parse_hierarchy_cidr

# Categories emitted by the established inventory writers, including the
# historical Clean Start categories. Unknown kinds are deliberately omitted.
_KIND_SECTIONS = {
    "Device": "Devices",
    "Device types": "Devices",
    "Locations": "Devices",
    "Settings": "Devices",  # Existing managed device catalogue/options writer.
    "IPAM": "IPAM",
    "Subnet": "IPAM",
    "VLAN": "IPAM",
    "Rack": "Racks",
    "IT Assets": "IT Assets",
    "Suppliers": "Suppliers",
}

# These reasons are generated by existing backend history writers. A legacy
# free-form reason must not reveal details from a hidden section.
_SAFE_REASONS = frozenset((
    "Inventory saved", "Bulk IPAM saved", "Clean inventory reset",
))


def visible_subnet_batch_reason(event):
    """Show authorised IPAM readers the complete count without forwarding free text.

    Rebuild this new summary only from bounded counts and valid network ranges.
    Existing mixed-event redaction and omitted-detail rules remain unchanged.
    """
    summary = event.get("subnetBatch")
    if (not isinstance(summary, dict) or set(summary) !=
            {"createdCount", "firstCidr", "lastCidr", "parentCidr"} or
            type(summary["createdCount"]) is not int or
            not 1 <= summary["createdCount"] <= 50 or
            not all(isinstance(change, dict) and change.get("kind") == "IPAM"
                    for change in event.get("changes", []))):
        return None
    first = parse_hierarchy_cidr(summary["firstCidr"], 23, 30)
    last = parse_hierarchy_cidr(summary["lastCidr"], 23, 30)
    if not first or not last or not first["aligned"] or not last["aligned"] or first["start"] > last["start"]:
        return None
    context = "No single Address Block"
    if summary["parentCidr"] is not None:
        parent = parse_hierarchy_cidr(summary["parentCidr"])
        if not parent or not parent["aligned"] or parent["start"] > first["start"] or parent["end"] < last["end"]:
            return None
        context = "IP Address Block " + summary["parentCidr"]
    return (f"Created {summary['createdCount']} subnet(s): "
            f"{summary['firstCidr']} – {summary['lastCidr']} · {context}")


def visible_change_history(connection, account_id):
    """Keep essential administrator events visible when inventory is disabled.

    Administrators with Devices, IPAM and Racks access retain complete events
    unless an event includes IT Assets changes they cannot read. Other events
    return only approved fields from readable sections and essential Account,
    Role and Security changes for verified admins. Unknown categories, extra
    details and omitted counts stay out of these restricted responses.
    """
    sections = {section: can_access(connection, account_id, section)
                for section in ("Devices", "IPAM", "Racks", "IT Assets", "Suppliers")}
    row = connection.execute(
        "SELECT active,is_admin,mfa_confirmed FROM accounts WHERE id=?",
        (account_id,),
    ).fetchone()
    is_admin = row == (1, 1, 1)
    if not is_admin and not any(sections.values()):
        return []
    complete_history = is_admin and all(sections[section] for section in ("Devices", "IPAM", "Racks"))

    last_operational_reset = 0
    if sections['IT Assets'] and not sections['Devices']:
        last_operational_reset = connection.execute("""
            SELECT coalesce(max(id),0) FROM inventory_change_history
            WHERE json_type(record_json,'$.operationalReset')='true'
              AND json_extract(record_json,'$.reason')='Clean inventory reset'
        """).fetchone()[0]
    history = []
    for event_id, raw in connection.execute(
            "SELECT id,record_json FROM inventory_change_history ORDER BY id"):
        event = json.loads(raw)
        if (isinstance(event, dict) and event.get("reason") == SUPPLIER_AUDIT_REASON
                and not feature_enabled(connection, "Suppliers")):
            continue
        reason = event.get('reason') if isinstance(event, dict) else None
        if reason in (CALENDAR_AUDIT_REASON, CATEGORY_AUDIT_REASON):
            if is_admin:
                history.append(event)
            continue
        if reason == SETTINGS_AUDIT_REASON:
            if is_admin and feature_enabled(connection, 'Equipment Lifecycle'):
                history.append(event)
            continue
        if reason in (DEVICE_AUDIT_REASON, FIRST_SERVICE_AUDIT_REASON) and not (
                sections['Devices'] and feature_enabled(connection, 'Equipment Lifecycle')):
            continue
        stock_changes = (isinstance(event, dict) and isinstance(event.get('changes'), list)
                         and any(isinstance(change, dict) and change.get('kind') == 'IT Assets'
                                 for change in event['changes']))
        supplier_changes = (isinstance(event, dict) and isinstance(event.get("changes"), list)
                            and any(isinstance(change, dict) and change.get("kind") == "Suppliers"
                                    for change in event["changes"]))
        # Issue corrections retain private original text. Verified administrators
        # with Suppliers access can inspect it independently of IT feature choices.
        supplier_issue_audit = (supplier_changes and len(event["changes"]) == 1
                                and isinstance(event.get("reason"), str)
                                and event["reason"].startswith("Supplier issue"))
        if supplier_issue_audit and is_admin and sections["Suppliers"]:
            history.append(event)
            continue
        if (complete_history and (sections["IT Assets"] or not stock_changes)
                and (sections["Suppliers"] or not supplier_changes)):
            history.append(event)
            continue
        if not isinstance(event, dict) or not isinstance(event.get("changes"), list):
            continue
        changes = []
        for change in event["changes"]:
            if not isinstance(change, dict):
                continue
            kind = change.get("kind")
            section = _KIND_SECTIONS.get(kind) if isinstance(kind, str) else None
            if ((section is not None and sections[section]) or
                    (is_admin and kind in ("Account", "Role", "Security"))):
                if kind=='IT Assets' and not sections['Devices']:
                    after=change.get('after') if isinstance(change.get('after'),dict) else {}
                    movement=after.get('movementId',after.get('closureMovementId'))
                    if after.get('deviceId') is not None:
                        continue
                    if type(movement) is int:
                        # The old ledger can no longer prove that the movement
                        # was independent of Devices. A reused ID cannot do so.
                        if event_id < last_operational_reset or connection.execute(
                                'SELECT 1 FROM it_asset_stock_entries e JOIN it_asset_stock_units u ON u.id=e.stock_unit_id '
                                'WHERE e.movement_id=? AND u.device_id IS NOT NULL LIMIT 1', (movement,),
                        ).fetchone():
                            continue
                # Never forward unrecognised historical payload properties.
                fields = change.get("fields")
                changes.append({
                    "kind": kind,
                    "action": change.get("action") if isinstance(change.get("action"), str) else "",
                    "label": change.get("label") if isinstance(change.get("label"), str) else "",
                    "fields": fields if isinstance(fields, list) and
                              all(isinstance(field, str) for field in fields) else [],
                })
        if not changes:
            continue
        visible_event = {"changes": changes, "omitted": 0}
        actor = event.get("actor")
        if isinstance(actor, str) and len(actor) <= 256:
            visible_event["actor"] = actor
        outcome = event.get("outcome")
        if outcome == "Succeeded":
            visible_event["outcome"] = outcome
        if isinstance(event.get("at"), str):
            visible_event["at"] = event["at"]
        reason = event.get("reason")
        if isinstance(reason, str) and reason in _SAFE_REASONS:
            visible_event["reason"] = reason
        if sections["IPAM"]:
            batch_reason = visible_subnet_batch_reason(event)
            if batch_reason:
                visible_event["reason"] = batch_reason
        history.append(visible_event)
    return history
