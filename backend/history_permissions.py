"""Permission-filtered inventory history for read-only API responses.

Keep stored events intact. Filter only the projected response so permission
changes apply immediately without a schema migration or history rewrite.
"""
import json

from .permissions import SECTIONS, can_access

# Categories emitted by the established inventory writers, including the
# historical Clean Start categories. Unknown kinds are deliberately omitted.
_KIND_SECTIONS = {
    "Device": "Devices",
    "Device types": "Devices",
    "Locations": "Devices",
    "Settings": "Devices",  # Existing managed device catalogue/options writer.
    "IPAM": "IPAM",
    "Subnet": "IPAM",
    "VLAN": "IPAM",
    "Rack": "Racks",
}

# These reasons are generated by existing backend history writers. A legacy
# free-form reason must not reveal details from a hidden section.
_SAFE_REASONS = frozenset((
    "Inventory saved", "Bulk IPAM saved", "Clean inventory reset",
))


def visible_change_history(connection, account_id):
    """Return only changes whose section the active account may currently read.

    Administrators retain the existing complete representation. Other users
    receive only approved event fields, and no ambiguous/unknown categories.
    The original `omitted` total cannot be assigned to a visible section, so
    it is not disclosed to partially privileged users.
    """
    sections = {section: can_access(connection, account_id, section)
                for section in SECTIONS}
    if not any(sections.values()):
        return []

    row = connection.execute(
        "SELECT active,is_admin,mfa_confirmed FROM accounts WHERE id=?",
        (account_id,),
    ).fetchone()
    is_admin = row == (1, 1, 1)

    history = []
    for (raw,) in connection.execute(
            "SELECT record_json FROM inventory_change_history ORDER BY id"):
        event = json.loads(raw)
        if is_admin:
            history.append(event)
            continue
        if not isinstance(event, dict) or not isinstance(event.get("changes"), list):
            continue
        changes = []
        for change in event["changes"]:
            if not isinstance(change, dict):
                continue
            kind = change.get("kind")
            section = _KIND_SECTIONS.get(kind) if isinstance(kind, str) else None
            if section is not None and sections[section]:
                # Never forward unrecognised historical payload properties.
                fields = change.get("fields")
                changes.append({
                    "kind": kind,
                    "action": change.get("action") if isinstance(change.get("action"), str) else "",
                    "label": change.get("label") if isinstance(change.get("label"), str) else "",
                    "fields": fields if isinstance(fields, list) and
                              all(isinstance(field, str) for field in fields) else [],
                })
        if not changes:
            continue
        visible_event = {"changes": changes, "omitted": 0}
        if isinstance(event.get("at"), str):
            visible_event["at"] = event["at"]
        reason = event.get("reason")
        if isinstance(reason, str) and reason in _SAFE_REASONS:
            visible_event["reason"] = reason
        history.append(visible_event)
    return history
