'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync(require('node:path').join(__dirname, 'caffoot-lite.html'), 'utf8');
const start = source.indexOf('        function findRackImportConflicts(');
const end = source.indexOf('        function validateAndNormaliseBackupForImport(', start);
assert.ok(start >= 0 && end > start, 'Import rack validator must exist');
// The import validator is self-contained; do not extract unrelated rack UI code.
const ctx = vm.createContext({});
vm.runInContext(source.slice(start, end) + '\nthis.check = findRackImportConflicts;', ctx);
const rack = {id:'r1',heightU:12};
const device = (id,face,start,height) => ({id,name:id,rackId:'r1',face,rackUStart:start,rackUHeight:height});
const acc = (id,type,face,start,height,side) => ({id,name:id,rackId:'r1',type,face,startU:start,heightU:height,side});
const check = (devices=[],rackAccessories=[],racks=[rack]) => Array.from(ctx.check({devices,rackAccessories,racks}));
assert.deepEqual(check([device('d1','front',2,2)],[acc('a1','patch','front',6,1),acc('v1','pdu_vertical','front',1,12,'left')]),[]);
assert.match(check([],[acc('a1','patch','front',2,2),acc('a2','blank','front',3,1)]).join(' '),/overlap/i);
assert.match(check([device('d1','front',2,2)],[acc('a1','patch','front',3,1)]).join(' '),/overlap/i);
assert.match(check([device('d1','front',2,2),device('d2','front',3,1)]).join(' '),/overlap/i);
assert.deepEqual(check([device('d1','front',2,2),device('d2','rear',2,2)]),[]);
assert.deepEqual(check([],[acc('a1','pdu_vertical','front',1,12,'left'),acc('a2','cable_vertical','front',1,12,'right')]),[]);
assert.match(check([],[acc('a1','pdu_vertical','front',1,12,'left'),acc('a2','cable_vertical','front',2,2,'left')]).join(' '),/overlap/i);
assert.match(check([],[{...acc('a1','patch','front',1,1),rackId:'missing'}]).join(' '),/missing rack/i);
assert.match(check([],[acc('a1','patch','front',12,2)]).join(' '),/invalid rack U/i);
assert.match(check([],[acc('a1','patch','side',1,1)]).join(' '),/invalid rack face/i);
assert.match(check([],[acc('a1','pdu_vertical','front',1,2,'middle')]).join(' '),/invalid side rail/i);
assert.match(check([],[acc('a1','unknown','front',1,1)]).join(' '),/unsupported accessory type/i);
assert.match(check([],[acc('a1','patch','front',1,1),acc('a1','patch','rear',1,1)]).join(' '),/duplicate ID/i);
assert.match(check([],[null]).join(' '),/invalid rack accessory record/i);
assert.deepEqual(check([],[]),[]);
console.log('PASS: imported rack occupancy, accessory shape, independent faces and rails.');
